// Generates the link-preview image (Open Graph `og:image`) that WhatsApp,
// Telegram, Facebook etc. show when someone shares a link to the site.
//
// Size and file name come from OG_IMAGE in src/config.js (1200x630, the
// landscape size those apps expect for a large preview), shared with the
// tags that declare them. The round logo badge sits centred on the site's
// dark background, so apps that crop to a square thumbnail (WhatsApp's small
// preview) still show the whole badge. Kept well under ~300KB: WhatsApp
// skips bigger images.
//
// Written to public/ so Vite copies it to dist/ unhashed, at the fixed URL
// the og:image tag (pageMetaTags plugin in vite.config.js) points to. Output
// is gitignored and regenerated by the "predev"/"prebuild" npm scripts.
import sharp from 'sharp';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { OG_IMAGE } from '../src/config.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.join(__dirname, '../src/assets/profile_img-02_circle.png');
const OUT_FILE = path.join(__dirname, '../public', OG_IMAGE.file);

const { width: WIDTH, height: HEIGHT } = OG_IMAGE;
const MARGIN = 30; // space above and below the badge
const BADGE_SIZE = HEIGHT - 2 * MARGIN;
const BACKGROUND = '#212529'; // Bootstrap's dark-theme body colour, as on the site

if (!existsSync(SOURCE)) {
    console.error(`[generate-og-image] source image not found: ${SOURCE}`);
    process.exitCode = 1;
} else {
    await mkdir(path.dirname(OUT_FILE), { recursive: true });

    const badge = await sharp(SOURCE)
        .resize({ width: BADGE_SIZE, height: BADGE_SIZE, fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
        .png()
        .toBuffer();

    await sharp({ create: { width: WIDTH, height: HEIGHT, channels: 3, background: BACKGROUND } })
        .composite([{ input: badge, gravity: 'centre' }])
        .jpeg({ quality: 82, mozjpeg: true })
        .toFile(OUT_FILE);

    console.log(`[generate-og-image] generated ${path.relative(process.cwd(), OUT_FILE)}`);
}
